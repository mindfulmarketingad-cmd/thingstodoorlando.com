export function getPost(slug: string): Post | undefined {
  return posts.find((p) => p.slug === slug);
}

export function readingMinutes(post: Post): number {
  return Math.max(3, Math.round(wordCount(post.body) / 220));
}

export function relatedPosts(post: Post, limit = 3): Post[] {
  const others = posts.filter((p) => p.slug !== post.slug);
  return [...others.filter((p) => p.category === post.category), ...others.filter((p) => p.category !== post.category)].slice(0, limit);
}

export function formatDate(iso: string): string {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
    timeZone: "UTC",
  });
}

/**
 * Featured image for a post: its own heroImage, then the Viator photo of its heroProduct when the
 * snapshot has one, otherwise the branded 1200x630 image generated by
 * scripts/generate-featured.mjs.
 */
export function featuredImage(slug: string) {
  const post = posts.find((p) => p.slug === slug);
  if (post?.heroImage) return { url: post.heroImage.src, width: post.heroImage.width, height: post.heroImage.height };
  const code = post?.heroProduct;
  const photo = code ? snapshotImage(code) : undefined;
  if (photo) return { url: photo.url, width: photo.width, height: photo.height };
  return { url: `/blog/${slug}.jpg`, width: 1200, height: 630 };
}

/** Map-and-layout posts, shown on the /maps hub. */
export function mapPosts(): Post[] {
  return posts.filter((p) => p.map).sort((a, b) => a.map!.park.localeCompare(b.map!.park));
}
